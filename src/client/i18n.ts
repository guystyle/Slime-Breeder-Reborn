export type I18nKey = Key;
const dict: Record<Lang, Record<Key, string>> = { ko, en };

let lang: Lang = 'ko';
try {
  const saved = localStorage.getItem('slime-lang');
  if (saved === 'ko' || saved === 'en') lang = saved;
} catch {
  /* storage unavailable: keep the default */
}

export const getLang = () => lang;
export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem('slime-lang', l);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = l;
}

/** Translate a key, filling {placeholders}. */
export function t(key: Key, params: Record<string, string | number> = {}): string {
  return dict[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ''));
}

/** Server error code -> text in the current language. */
export function errorText(code: ErrorCode | string, params: Record<string, string | number> = {}): string {
  const key = `err.${code}` as Key;
  return key in dict[lang] ? t(key, params) : t('err.server');
}

