#!/usr/bin/env python3
"""
Convert the SLIME BREEDER plus v1.08 sprite GIFs into data-URI PNG pairs for the web client.

Each GIF has a transparent body (the slime colour shows through), an opaque
teal (#003f3f) backdrop and opaque details (eyes, highlights, wings...). We split it into
  - `body`: white where the GIF is transparent  -> used as a CSS mask over the genetic colour
  - `art` : every other opaque pixel, teal removed -> drawn on top
The GIFs are tatuta's artwork, used under the redistribution terms in NOTICE.md.

usage: convert_sprites.py <dir with slm*.gif> <output .ts file>
"""
import base64, io, sys
from PIL import Image

KINDS = {  # kind -> gif name
    'normal': 'normal', 'aura': 'aura', 'hider': 'hider', 'wing': 'wing', 'ribbon': 'ribbon',
    'ribbonw': 'ribbonw', 'crown': 'crown', 'crownw': 'crownw', 'aho': 'aho', 'zombie': 'zombie',
    'oyaji': 'oyaji', 'musi': 'musi', 'angel': 'angel', 'devil': 'devil',
}
TEAL = (0, 63, 63)


def uri(img: Image.Image) -> str:
    buf = io.BytesIO()
    img.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


def split(path: str):
    rgba = Image.open(path).convert('RGBA')
    w, h = rgba.size
    body = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    art = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    bp, ap, sp = body.load(), art.load(), rgba.load()
    for y in range(h):
        for x in range(w):
            r, g, b, a = sp[x, y]
            if a == 0:
                bp[x, y] = (255, 255, 255, 255)
            elif (r, g, b) != TEAL:
                ap[x, y] = (r, g, b, 255)
    return body, art


def main(src: str, out: str):
    lines = ['// GENERATED by scripts/convert_sprites.py from SLIME BREEDER plus v1.08 artwork (c) tatuta. See NOTICE.md.',
             "import type { Kind } from '../shared/dna.ts';", '',
             'export const SPRITES: Record<Kind, { body: string; art: string }> = {']
    for kind, gif in KINDS.items():
        body, art = split(f'{src}/slm{gif}.gif')
        lines.append(f"  {kind}: {{\n    body: '{uri(body)}',\n    art: '{uri(art)}',\n  }},")
    lines.append('};')
    for name in ('bg', 'bg2'):
        im = Image.open(f'{src}/slm{name}.gif').convert('RGB')
        lines.append(f"\n/** tiled panel background strip (slm{name}.gif) */\nexport const {name.upper()}_STRIP = '{uri(im)}';")
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
