#!/usr/bin/env node
/**
 * Bundle the API into one self-contained file for Vercel: api/[...path].js
 * (Vercel's per-file TypeScript builder is fragile with ESM + relative imports; one file avoids that).
 * Commit the result; `npm run build` regenerates it.
 */
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const path = (p) => fileURLToPath(new URL(p, root));

// `--check` verifies the committed bundle is current instead of writing it
const check = process.argv.includes('--check');
const out = path('api/[...path].js');

const result = await build({
  write: !check,
  entryPoints: [path('src/server/vercel.ts')],
  outfile: out,
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  legalComments: 'none',
  logLevel: 'info',
  // node:* built-ins stay external. Only the bare '@libsql/client' (native, file: URLs) is stubbed;
  // '@libsql/client/web' (the HTTP client Vercel uses) is bundled for real.
  plugins: [
    {
      name: 'stub-native-libsql',
      setup(b) {
        b.onResolve({ filter: /^@libsql\/client$/ }, () => ({ path: path('scripts/libsql-native-stub.mjs') }));
      },
    },
  ],
  external: ['bufferutil', 'utf-8-validate'],
  banner: { js: '// GENERATED by scripts/build-api.mjs from src/server — do not edit.\nimport { createRequire as __cr } from "node:module"; const require = __cr(import.meta.url);' },
});

if (check) {
  const fresh = Buffer.from(result.outputFiles[0].contents);
  let have;
  try {
    have = readFileSync(out);
  } catch {
    have = Buffer.alloc(0);
  }
  if (!fresh.equals(have)) {
    console.error('api/[...path].js is out of date. Run `npm run build:api` and commit the result.');
    process.exit(1);
  }
  console.log('api/[...path].js is up to date.');
}
